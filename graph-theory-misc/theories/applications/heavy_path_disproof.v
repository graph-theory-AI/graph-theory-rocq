Qed.

Lemma yy_adj (a b : HG) : isY a -> isY b -> a != b -> a -- b.
Proof. by case: a => [//|[k|//]]; case: b => [//|[k'|//]] _ _ ne; apply: contra ne => /eqP ->. Qed.

Lemma xc_adj (a : HG) : isC a -> xv -- a.
Proof. by case: a. Qed.

Lemma count_isY_le2 (d : seq HG) : hole d -> count isY d <= 2.
