(** * ClassicalLemmas.chains — finitely supported chains over a ring

    For a finite type [cell] of cells and a ring [R], a chain is a finitely
    supported function [cell -> R], i.e. a finite function.  mathcomp already
    equips [{ffun cell -> R^o}] with its [lmodType R] structure, so sums and
    scalar multiples come for free; this file only adds the basis chains [cc x]
    and the linear extension [lin f] of a map [f] defined on cells, together
    with the lemmas needed to reason "cell by cell". *)

