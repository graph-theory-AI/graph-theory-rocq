"""ck_path chain renderer (arthur, phase-2 DRAFT for Lancelot 20e0b09e; NOT RUN; r2 for addendum-1 C1/C3): one module that renders
  * the TWO committed block formats and the committed final, exactly (used by the round-trip check of the transform):
      explicit  = digraph-theory/scripts/generate_ckpath_certificates.py write_rocq_chain_block at R 8837973e (union3/4/5)
      selected  = the older writer of cover4 and the 19 low3 groups (not in the repo; its layout read from the committed files)
      final     = write_rocq_chain_final at R
  * the NEW layout (DESIGN.md b of ckpath-restructure-design-by-arthur, 7e8d05aa):
      <g>_<label>_data.v   data only: the block output
      <g>_<label>.v        the replay in hypothesis form (imports its own data and its producers' data, never their replays)
      <g>_assembly.v       the group's chain of <name>_<label>_sound lemmas, today's statements
      <g>_final.v          today's final, importing the assembly and the last block's data module
Every data literal (output cnf, selected_base cnf, base_ids list, records, index lists) is carried as the RAW TEXT sliced from the
committed file; nothing here re-serialises a clause.  Used by restructure_ckpath_chains.py and (for the explicit format) by the generator."""
from __future__ import annotations

from dataclasses import dataclass, field

GEN = "(** Generated by [scripts/generate_ckpath_certificates.py]"
OLD_BLOCK_HEADER = (
    GEN + ".\n"
    "    Only the block output is transparent.  Selected base clauses,\n"
    "    producer imports, replay records, and the transient database\n"
    "    all remain underneath the opaque soundness theorem. *)\n\n")
OLD_FINAL_HEADER = (
    GEN + ".\n"
    "    The complete microblock chain ends in the empty clause. *)\n\n")
CHECKER = {'explicit': ('ckpath_drup_explicit_microblock', 'check_explicit_microblock', 'selected_base'),
           'selected': ('ckpath_drup_microblock', 'check_selected_microblock', 'base_ids')}


@dataclass
class Selection:
    label: str            # the producer's block label, e.g. 'block07'
    indices: str          # raw text, e.g. '[22;5;6;0]'


@dataclass
class Block:
    fmt: str              # 'explicit' | 'selected'
    group: str            # module prefix, e.g. 'ckpath_cert_k7_c12_low3_mask17'
    label: str            # 'block03'
    name: str             # Rocq name prefix, e.g. 'c12_k7_low3_mask17'
    base_module: str
    base: str             # the base expression, raw (inside the outer parentheses)
    counts: tuple         # (a, b, nb, ni, np) from the generated comment, as strings
    base_ids_comment: str | None   # explicit only: the '[...]' list of original selected base identifiers
    selected_base: str | None      # explicit only: raw cnf text '[\n  ...\n]'
    base_ids: str | None           # selected only: raw '[...]' nat list
    output: str           # raw cnf text
    records: str          # raw text between 'pose ([\n' and '] : list (list nat * list nat)) as records.'
    selections: list = field(default_factory=list)   # [Selection], in the committed order

    def module(self, label=None):
        return '%s_%s' % (self.group, label or self.label)

    def out(self, label=None):
        return '%s_%s_output' % (self.name, label or self.label)

    def sound(self, label=None):
        return '%s_%s_sound' % (self.name, label or self.label)

    def replay(self, label=None):
        return '%s_%s_replay' % (self.name, label or self.label)

    def comment(self):
        a, b, nb, ni, np = self.counts
        head = '(** Original retained additions [%s, %s); %s selected base clauses and %s imported consequences from %s producer blocks.' % (a, b, nb, ni, np)
        if self.fmt == 'explicit':
            return head + '\n    Original selected base identifiers: %s. *)\n' % self.base_ids_comment
        return head + ' *)\n'


@dataclass
class Final:
    group: str
    name: str
    base_module: str
    last_label: str
    base: str
    rights: int           # the number of '  right.' lines (the last block's output length minus one)


def _prelude(imports, extra=''):
    return ('From Stdlib Require Import List.\n'
            'From Digraph Require Import %s.\n' % ' '.join(imports) + extra +
            'Import ListNotations.\n'
            'Set Warnings "-abstract-large-number".\n\n')


# ---------------------------------------------------------------- the committed forms (round-trip)
def render_old_block(b: Block) -> str:
    checker_module, check, sel = CHECKER[b.fmt]
    s = OLD_BLOCK_HEADER + _prelude(['ckpath_cnf', checker_module, b.base_module] + [b.module(x.label) for x in b.selections]) + b.comment()
    if b.fmt == 'explicit':
        s += 'Definition selected_base : cnf :=\n  ' + b.selected_base + '.\n\n'
    s += 'Definition %s : cnf :=\n  %s.\n\n' % (b.out(), b.output)
    s += ('Theorem %s :\n  forall rho, satisfies_cnf rho (%s) ->\n    satisfies_cnf rho %s.\nProof.\nintros rho Hbase.\n'
          % (b.sound(), b.base, b.out()))
    for x in b.selections:
        pl, po, ps = x.label, b.out(x.label), b.sound(x.label)
        s += ('pose (select_cnf %s %s : cnf)\n  as imported_from_%s.\n'
              'assert (Himported_from_%s :\n  satisfies_cnf rho imported_from_%s).\n'
              '{\n  unfold imported_from_%s.\n  apply (satisfies_cnf_select rho %s %s).\n'
              '  - exact (%s rho Hbase).\n  - vm_compute. reflexivity.\n}\n' % (po, x.indices, pl, pl, pl, pl, po, x.indices, ps))
    s += ('pose (concat [%s] : cnf) as imported.\n' % ';'.join('imported_from_' + x.label for x in b.selections) +
          'assert (Himported : satisfies_cnf rho imported).\n{\n  unfold imported.\n  apply satisfies_cnf_concat_intro.\n' +
          ''.join('  constructor.\n  { exact Himported_from_%s. }\n' % x.label for x in b.selections) + '  constructor.\n}\n')
    if b.fmt == 'selected':
        s += 'pose (\n  %s : list nat) as base_ids.\n' % b.base_ids
    s += 'pose ([\n' + b.records + '] : list (list nat * list nat)) as records.\n'
    s += ('assert (Hcheck :\n  %s (%s) %s\n    imported records %s = true).\n{ vm_compute. reflexivity. }\n'
          'exact (%s_sound\n  (%s) %s imported records %s\n  Hcheck rho Hbase Himported).\nQed.\n'
          % (check, b.base, sel, b.out(), check, b.base, sel, b.out()))
    return s


def render_old_final(f: Final) -> str:
    out, sound = '%s_%s_output' % (f.name, f.last_label), '%s_%s_sound' % (f.name, f.last_label)
    return (OLD_FINAL_HEADER + 'From Stdlib Require Import List.\n'
            'From Digraph Require Import ckpath_cnf %s %s_%s.\n' % (f.base_module, f.group, f.last_label) +
            'Import ListNotations.\n\n'
            'Theorem %s_base_unsatisfiable :\n  forall rho, ~ satisfies_cnf rho (%s).\nProof.\nintros rho Hbase.\n' % (f.name, f.base) +
            'pose proof (%s rho Hbase) as Hlast.\n' % sound +
            'assert (Hin : In [] %s).\n{\n  unfold %s.\n' % (out, out) + '  right.\n' * f.rights + '  left. reflexivity.\n}\n'
            'pose proof (eval_cnf_member rho %s [] Hlast Hin) as Hfalse.\n' % out +
            'unfold eval_clause in Hfalse. discriminate.\nQed.\n')


# ---------------------------------------------------------------- the new layout
NEW_DATA_HEADER = GEN + " (restructured layout).\n    Data only: the output clauses of one replay block. *)\n\n"
NEW_REPLAY_HEADER = (GEN + " (restructured layout).\n"
                     "    One replay block in hypothesis form: its producers' selected clauses are a\n"
                     "    hypothesis, so it needs their output data only, never their proofs. *)\n\n")
NEW_ASSEMBLY_HEADER = (GEN + " (restructured layout).\n"
                       "    The group's soundness lemmas, in block order: each applies its block's replay to\n"
                       "    its producers' selected clauses, derived from the producers' lemmas above. *)\n\n")


def imported_expr(b: Block, indent='      ') -> str:
    if not b.selections:
        return 'concat []'
    return 'concat [\n' + ';\n'.join('%sselect_cnf %s %s' % (indent, b.out(x.label), x.indices) for x in b.selections) + ']'


def render_data(b: Block) -> str:
    return NEW_DATA_HEADER + _prelude(['ckpath_cnf']) + 'Definition %s : cnf :=\n  %s.\n' % (b.out(), b.output)


def render_replay(b: Block) -> str:
    checker_module, check, sel = CHECKER[b.fmt]
    extra = 'From Digraph Require Export %s_data.\n' % b.module()
    if b.selections:
        extra += 'From Digraph Require Import %s.\n' % ' '.join(b.module(x.label) + '_data' for x in b.selections)
    s = NEW_REPLAY_HEADER + _prelude(['ckpath_cnf', checker_module, b.base_module], extra) + b.comment()
    if b.fmt == 'explicit':
        s += 'Definition selected_base : cnf :=\n  ' + b.selected_base + '.\n\n'
    imp = imported_expr(b)
    s += ('Theorem %s :\n  forall rho, satisfies_cnf rho (%s) ->\n    satisfies_cnf rho (%s) ->\n    satisfies_cnf rho %s.\n'
          'Proof.\nintros rho Hbase Himported.\n' % (b.replay(), b.base, imp, b.out()))
    if b.fmt == 'selected':
        s += 'pose (\n  %s : list nat) as base_ids.\n' % b.base_ids
    s += 'pose ([\n' + b.records + '] : list (list nat * list nat)) as records.\n'
    s += ('assert (Hcheck :\n  %s (%s) %s\n    (%s) records %s = true).\n{ vm_compute. reflexivity. }\n'
          'exact (%s_sound\n  (%s) %s (%s) records %s\n  Hcheck rho Hbase Himported).\nQed.\n'
          % (check, b.base, sel, imp, b.out(), check, b.base, sel, imp, b.out()))
    return s


def render_assembly(blocks: list) -> str:
    """blocks: one group's Blocks in increasing label order (the transform checks the order and that producers precede)"""
    b0 = blocks[0]
    checker_module = CHECKER[b0.fmt][0]
    s = (NEW_ASSEMBLY_HEADER + 'From Stdlib Require Import List.\n'
         'From Digraph Require Import ckpath_cnf %s %s.\n' % (checker_module, b0.base_module) +
         ''.join('From Digraph Require Import %s.\n' % b.module() for b in blocks) + 'Import ListNotations.\n'
         'Set Warnings "-abstract-large-number".\n\n')       # r2 (C3): the same warnings line as the other kinds
    for b in blocks:
        s += ('Theorem %s :\n  forall rho, satisfies_cnf rho (%s) ->\n    satisfies_cnf rho %s.\nProof.\nintros rho Hbase.\n'
              'apply (%s rho Hbase).\napply satisfies_cnf_concat_intro.\n' % (b.sound(), b.base, b.out(), b.replay()))
        for x in b.selections:
            s += ('constructor.\n{ apply (satisfies_cnf_select rho %s %s).\n  - exact (%s rho Hbase).\n  - vm_compute. reflexivity. }\n'
                  % (b.out(x.label), x.indices, b.sound(x.label)))
        s += 'constructor.\nQed.\n\n'
    return s


def render_new_final(f: Final) -> str:
    """today's final, byte for byte, except its Require line: the assembly (for the _sound lemma) and the last block's data module
    (for the _output definition it unfolds; a Require Import of the assembly alone does not bring the data module's names into scope)"""
    old = render_old_final(f)
    old_req = 'From Digraph Require Import ckpath_cnf %s %s_%s.\n' % (f.base_module, f.group, f.last_label)
    new_req = 'From Digraph Require Import ckpath_cnf %s %s_assembly %s_%s_data.\n' % (f.base_module, f.group, f.group, f.last_label)
    assert old.count(old_req) == 1
    return old.replace(old_req, new_req)
