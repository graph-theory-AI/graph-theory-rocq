(** * Every positive symmetric length assignment on G8 has a non-peripheral geodesic cycle *)
Section Main.
Variable R : realFieldType.

(** The tie-breaking weights: a spoke s_i b_j gets i + 1, a core edge gets 0. *)
Definition gam8 (x y : G8) : R :=
  (if x.1 then (x.2 : nat).+1 else 0)%:R + (if y.1 then (y.2 : nat).+1 else 0)%:R.

Lemma gam8_sym x y : gam8 x y = gam8 y x.
Proof. by rewrite /gam8 addrC. Qed.

Lemma gam8_ge0 x y : 0 <= gam8 x y.
Proof. by rewrite /gam8 addr_ge0 ?ler0n. Qed.

Lemma gam8_le x y : gam8 x y <= 8%:R.
Proof.
rewrite /gam8 -natrD ler_nat.
have h : forall v : G8, ((if v.1 then (v.2 : nat).+1 else 0) <= 4)%N.
  by move=> [[] i] //=; exact: ltn_ord.
by rewrite (leq_trans (leq_add (h x) (h y))).
Qed.

Variable ell : G8 -> G8 -> R.
Hypothesis hl : edge_length ell.
Hypothesis hA : forall c, geodesic_cycle ell c -> peripheral_cycle c.

Let W := wpert ell gam8 8%:R.
Let hW : edge_length W := edge_length_pert hl gam8_sym gam8_ge0 (ler0n _ 8).
Let hA' c (g : geodesic_cycle W c) : peripheral_cycle c :=
  hA (geodesic_pert hl gam8_sym gam8_ge0 gam8_le (ler0n _ 8) g).

Lemma T_tight_geo (i : 'I_4) :
  (forall j k : 'I_4, j != i -> k != i -> j != k -> tightb W (false, j) (false, k)) ->
  geodesic_cycle W (Tseq i).
Proof.
move=> ht; have := allI4 check_T_ok i; cbv beta => /and5P[tT _ uT /allP memT /allP consT].
split; first by rewrite /ucycle uT andbT; move: tT; rewrite /tri /Tseq /= andbT.
move=> u v uin vin; case: (eqVneq u v) => [<-|uv].
  by exists [::]; split; [exact: shortest_nil|].
have := memT u (mem_V8 u); rewrite uin => /eqP/esym/andP[u1 ui].
have := memT v (mem_V8 v); rewrite vin => /eqP/esym/andP[v1 vi].
have cuv := consT u (mem_V8 u); move/allP: cuv => /(_ v (mem_V8 v)); rewrite uin vin uv /= => cuv.
move: u v uin vin uv u1 ui v1 vi cuv => [[] a] [[] b] //= uin vin uv _ ai _ bi cuv.
have ab : a != b by apply: contra uv => /eqP ->.
exists [:: (false, b)]; split; last by rewrite on_cycle_walk_steps /= cuv.
apply/(tightP hW); last exact: ht.
by rewrite /edge_rel /= /g8_adj /= ab.
Qed.

Lemma nontight_T (i : 'I_4) :
  exists j k : 'I_4, [/\ j != i, k != i, j != k & ~~ tightb W (false, j) (false, k)].
Proof.
case: (boolP [exists j, [exists k, [&& j != i, k != i, j != k & ~~ tightb W (false, j) (false, k)]]]).
  by case/existsP => j /existsP[k /and4P[? ? ? ?]]; exists j, k.
rewrite negb_exists => /forallP h; exfalso.
have tg : geodesic_cycle W (Tseq i).
  apply: T_tight_geo => j k ji ki jk.
  by move: (h j); rewrite negb_exists => /forallP/(_ k); rewrite ji ki jk /= negbK.
have := allI4 check_T_ok i; cbv beta => /and5P[tT bT _ _ _].
exact: (allB_not_peripheral tT bT (hA' tg)).
Qed.

Lemma wlen2 (f : G8 -> G8 -> R) u a b : wlen f u [:: a; b] = f u a + f a b.
Proof. by rewrite wlenE !slen_cons slen_nil addr0. Qed.

Lemma face_of_edge (j k : 'I_4) : j != k -> ~~ tightb W (false, j) (false, k) ->
  exists a : 'I_4 * 'I_4, [/\ a.1 != a.2, face_mem a (false, j), face_mem a (false, k) &
    forall C, ucycle (--) C -> (forall x, x \in C -> face_mem a x) ->
      (false, j) \in C -> (false, k) \in C -> ~ geodesic_cycle W C].
Proof.
move=> jk nt.
have := allI4 (allI4 check_oth_ok j) k; cbv beta.
move=> /implyP/(_ jk) /and5P[pq /allP memc fj fk /andP[gj gk]].
have := allI4 (allI4 check_oth2_ok j) k; cbv beta => /implyP/(_ jk) /allP o2.
move: pq memc fj fk gj gk o2.
set p := (oth (j, k)).1; set q := (oth (j, k)).2 => pq memc fj fk gj gk o2.
have nojk : forall s, s \in [:: p; q] -> (s != j) && (s != k).
  move=> s sm; have := memc s (mem_I4 s); rewrite sm => /eqP/esym.
  by rewrite !inE negb_or.
(* the face on the side of the longer 2-path is not geodesic *)
have side : forall s s', s \in [:: p; q] -> s' \in [:: p; q] ->
    (forall x, face_mem (s, s') x -> x \in [:: (true, s); (false, j); (false, k)]) ->
    wlen W (false, j) [:: (true, s'); (false, k)] < wlen W (false, j) [:: (true, s); (false, k)] ->
    forall C, ucycle (--) C -> (forall x, x \in C -> face_mem (s, s') x) ->
      (false, j) \in C -> (false, k) \in C -> ~ geodesic_cycle W C.
  move=> s s' sm s'm fm lt C uC sub jC kC [_ g].
  have [p0 [sp op]] := g _ _ jC kC.
  have up := shortest_uniq hW sp; have lp := shortest_last sp.
  have sub' : {subset p0 <= [:: (true, s); (false, k)]}.
    move=> x xp; have := fm x (sub x (on_cycle_sub op xp)).
    rewrite !inE => /or3P[->|/eqP xj|->]; rewrite ?eqxx ?orbT //.
    by move: up; rewrite /= -xj xp.
  have jkv : ((false, j) : G8) != (false, k) by apply: contra jk => /eqP[->].
  have skv : ((true, s) : G8) != (false, k) by [].
  have /andP[s'j s'k] := nojk s' s'm.
  case: (walk2_shape up lp jkv skv sub') => e; subst p0.
    move/negP: nt; apply; apply/(tightP hW) => //.
    by rewrite /edge_rel /= /g8_adj /= jk.
  case: sp => _ _ /(_ [:: (true, s'); (false, k)]) h.
  have : wlen W (false, j) [:: (true, s); (false, k)] <=
         wlen W (false, j) [:: (true, s'); (false, k)].
    by apply: h => //; rewrite /= /edge_rel /= /g8_adj /= eq_sym s'j s'k.
  by rewrite leNgt lt.
have pm : p \in [:: p; q] by exact: mem_head.
have qm : q \in [:: p; q] by rewrite !inE eqxx orbT.
(* the perturbation separates the two 2-paths *)
have sep : wlen W (false, j) [:: (true, p); (false, k)] !=
           wlen W (false, j) [:: (true, q); (false, k)].
  apply: (pert_separates ell gam8_ge0 gam8_le (ler0n _ 8)).
  - by rewrite /= !inE !xpair_eqE /= (negbTE jk).
  - by rewrite /= !inE !xpair_eqE /= (negbTE jk).
  rewrite !wlen2 /gam8 /= -!natrD eqr_nat !add0n !addn0.
  by rewrite !addnn (inj_eq double_inj) eqSS.
have fq : forall x, face_mem (q, p) x -> x \in [:: (true, q); (false, j); (false, k)].
  by move=> x; have /andP[_ /implyP] := o2 x (mem_V8 x).
have fp : forall x, face_mem (p, q) x -> x \in [:: (true, p); (false, j); (false, k)].
  by move=> x; have /andP[/implyP h _] := o2 x (mem_V8 x).
case: (ltgtP (wlen W (false, j) [:: (true, p); (false, k)])
             (wlen W (false, j) [:: (true, q); (false, k)])) => h.
- by exists (q, p); split => //=; [rewrite eq_sym | exact: side].
- by exists (p, q); split => //=; exact: side.
- by move: sep; rewrite h eqxx.
Qed.

Lemma main_false : False.
Proof.
(* two distinct non-tight core edges, and on each a face that is not geodesic *)
have [j [k [j0 k0 jk ntjk]]] := nontight_T ord0.
have [j' [k' [j'j k'j j'k' nt']]] := nontight_T j.
have [a [aF aj ak nga]] := face_of_edge jk ntjk.
have [b [bF bj' bk' ngb]] := face_of_edge j'k' nt'.
have ab : a != b.
  apply/eqP => e; subst b.
  have := allI4 (allI4 (allI4 (allfaces check_distinct_ok aF) j) j') k'; cbv beta.
  by rewrite eq_sym j'j eq_sym k'j j'k' aj bj' bk'.
(* the parity functional separating the faces a and b from the others *)
pose D := fun x y => Dface a x y (+) Dface b x y.
have Dsym : symmetric D by move=> x y; rewrite /D Dface_sym [Dface b _ _]Dface_sym.
have par : forall (c : 'I_4 * 'I_4) x y z, c.1 != c.2 -> tri x y z -> ~~ allB x y z ->
    odd (dc (Dface c) [:: x; y; z]) = infa c x y z (+) infa root x y z.
  move=> c x y z cF t nb.
  have := allV8 (allV8 (allV8 (allfaces check_par_ok cF) x) y) z; cbv beta.
  by move=> /implyP/(_ (introT andP (conj t nb))) /eqP <-; rewrite dc3.
have parD : forall x y z, tri x y z -> ~~ allB x y z ->
    odd (dc D [:: x; y; z]) = infa a x y z (+) infa b x y z.
  move=> x y z t nb; rewrite /D odd_dc_xor (par a) // (par b) //.
  by rewrite addbACA addbb addbF.
have := allfaces check_faces_ok aF; cbv beta => /and5P[cyc _ /allP infab _ _].
have t0 : tri (true, a.1) (false, (oth a).1) (false, (oth a).2) by exact: tri_of_cycle.
have o0 : odd (dc D (face_seq a)).
  rewrite /face_seq parD //.
  have := infab a; rewrite mem_faces => /(_ aF) /eqP ->.
  have := infab b; rewrite mem_faces => /(_ bF) /eqP ->.
  by rewrite eqxx eq_sym (negbTE ab).
(* the minimal odd closed walk is a geodesic cycle, hence peripheral, hence a face triangle *)
have [C [gC oC sC]] := min_odd hW Dsym cyc o0.
have pC := hA' gC.
have s3 := no_long_chordless pC.1.
case: C gC oC sC pC s3 => [|x [|y [|z [|w r]]]] // gC oC _ pC _.
have uC : ucycle (--) [:: x; y; z] := gC.1.
have t : tri x y z by apply: tri_of_cycle; case/andP: uC.
have nb : ~~ allB x y z by apply/negP => abC; exact: (allB_not_peripheral t abC pC).
rewrite parD // in oC.
have cont_of : forall c, c.1 != c.2 -> infa c x y z ->
    forall s : 'I_4, face_mem c (false, s) -> ((false, s) : G8) \in [:: x; y; z].
  move=> c cF ic s fs.
  have := allfaces check_faces_ok cF; cbv beta => /and5P[_ _ _ _ /allP cnt].
  have := cnt x (mem_V8 x); move/allP => /(_ y (mem_V8 y)) /allP /(_ z (mem_V8 z)).
  by move=> /implyP/(_ (introT andP (conj t ic))) /allP /(_ s (mem_I4 s)) /implyP; apply.
have sub_of : forall c, infa c x y z -> forall v, v \in [:: x; y; z] -> face_mem c v.
  by move=> c /and3P[hx hy hz] v; rewrite !inE => /or3P[] /eqP ->.
(* odd parity puts C in face a or in face b, neither of which is geodesic *)
case: (boolP (infa a x y z)) => ia.
  exact: (nga _ uC (sub_of a ia) (cont_of a aF ia j aj) (cont_of a aF ia k ak) gC).
have ib : infa b x y z by move: oC; rewrite (negbTE ia).
exact: (ngb _ uC (sub_of b ib) (cont_of b bF ib j' bj') (cont_of b bF ib k' bk') gC).
Qed.

End Main.

Theorem g8_geodesic_not_peripheral (R : realFieldType) (ell : G8 -> G8 -> R) :
  edge_length ell -> ~ (forall c : seq G8, geodesic_cycle ell c -> peripheral_cycle c).
