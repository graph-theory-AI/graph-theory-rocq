Lemma no_long_chordless (c : seq G8) : chordless_ucycle c -> (size c <= 3)%N.
Proof.
move=> ch; rewrite leqNgt; apply/negP => sz.
case: (boolP (has (fun v : G8 => v.1) c)) => [/hasP[s sc s1]|hB].
- (* a spoke vertex s: rotate it to the front; its two cycle neighbours are core vertices *)
  have ch' := (chordless_ucycle_rot (index s c) c).2 ch.
  have szr : size (rot (index s c) c) = size c by rewrite size_rot.
  rewrite (rot_index sc) in ch' szr.
  move: ch' szr; set t := drop _ _ ++ take _ _ => ch' szr.
  rewrite -szr in sz; clear szr; clearbody t.
  case: t ch' sz => [|t1 [|t2 [|t3 t'']]] //= ch' _.
  case: ch' => /andP[cc uc] chl.
  set l := last t3 t''.
  have st1 : s -- t1 by case/andP: cc.
  have ls : l -- s.
    by move: cc => /= /and4P[_ _ _]; rewrite rcons_path => /andP[_].
  have t1B := S_adj_B s1 st1.
  have lB : ~~ l.1 by apply: (S_adj_B s1); rewrite sg_sym.
  have lin : l \in t3 :: t'' by exact: mem_last.
  have t1l : t1 != l.
    apply/eqP => e; move: uc; rewrite /= -e in lin.
    by case/andP=> _ /andP[/negP nt1 _]; apply: nt1; rewrite in_cons lin orbT.
  have t1in : t1 \in [:: s, t1, t2, t3 & t''] by rewrite !inE eqxx orbT.
  have lin' : l \in [:: s, t1, t2, t3 & t''] by rewrite in_cons in_cons in_cons lin !orbT.
  have := chl t1 l t1in lin' (B_adj t1B lB t1l).
  rewrite cyc_edgeE /cyc_steps.
  have p1 : (t1, t2) \in zip [:: s, t1, t2, t3 & t''] (rot 1 [:: s, t1, t2, t3 & t'']).
    by rewrite rot1_cons /= !inE eqxx !orbT.
  have p2 : (l, s) \in zip [:: s, t1, t2, t3 & t''] (rot 1 [:: s, t1, t2, t3 & t'']).
    by rewrite -/(cyc_steps _) cyc_steps_cons steps_rcons mem_rcons inE eqxx.
  case/orP => [h|h].
    have e := next_eq uc h p1.
    rewrite e in lin; move: uc.
    by case/andP=> _ /andP[_ /andP[/negP nt2 _]]; apply: nt2.
  have e := next_eq uc h p2.
  move: uc; rewrite -e.
  by case/andP=> /negP ns _; apply: ns; exact: mem_head.
- (* only core vertices: x0 and x2 are adjacent and not consecutive *)
  case: c ch sz hB => [|x0 [|x1 [|x2 [|x3 r]]]] //= ch _ hB.
  case: ch => /andP[cc uc] chl.
  move: hB; rewrite negb_or => /andP[b0]; rewrite negb_or => /andP[b1].
  rewrite negb_or => /andP[b2 _].
  have x02 : x0 != x2.
    by move: uc => /andP[]; rewrite !inE negb_or => /andP[_]; rewrite negb_or => /andP[].
  have p1 : (x0, x1) \in zip [:: x0, x1, x2, x3 & r] (rot 1 [:: x0, x1, x2, x3 & r]).
    by rewrite rot1_cons /= !inE eqxx.
  have p2 : (x2, x3) \in zip [:: x0, x1, x2, x3 & r] (rot 1 [:: x0, x1, x2, x3 & r]).
    by rewrite rot1_cons /= !inE eqxx !orbT.
  have x2in : x2 \in [:: x0, x1, x2, x3 & r] by rewrite !inE eqxx !orbT.
  have := chl x0 x2 (mem_head _ _) x2in (B_adj b0 b2 x02).
  rewrite cyc_edgeE /cyc_steps; case/orP => h.
    have e := next_eq uc h p1.
    by move: uc; rewrite e; case/andP=> _ /andP[/negP nx1 _]; apply: nx1; exact: mem_head.
  have e := next_eq uc h p2.
  move: uc; rewrite e; case/andP=> /negP nx0 _; apply: nx0.
  by rewrite !inE eqxx !orbT.
