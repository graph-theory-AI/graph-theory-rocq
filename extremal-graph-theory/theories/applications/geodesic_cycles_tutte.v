(** * Steps of a walk and sums over them *)
Section Steps.
Variable T : Type.

Definition steps (u : T) (p : seq T) : seq (T * T) := zip (u :: p) p.

Lemma steps_cons u x p : steps u (x :: p) = (u, x) :: steps x p.
Proof. by []. Qed.

Lemma steps_cat u p q : steps u (p ++ q) = steps u p ++ steps (last u p) q.
Proof. by elim: p u => [|x p IH] u //=; rewrite steps_cons IH. Qed.

Lemma steps_rcons u p x : steps u (rcons p x) = rcons (steps u p) (last u p, x).
Proof. by rewrite -cats1 steps_cat cats1. Qed.

Lemma size_steps u p : size (steps u p) = size p.
Proof. by rewrite /steps size_zip; apply/minn_idPr; apply: leqnSn. Qed.

Lemma last_rev_belast (u : T) p : last (last u p) (rev (belast u p)) = u.
Proof.
by rewrite -[last _ (rev _)]/(last u (last u p :: rev (belast u p))) -rev_rcons -lastI
  rev_cons last_rcons.
Qed.

Definition swap_step (e : T * T) : T * T := (e.2, e.1).

Lemma steps_rev u p :
  steps (last u p) (rev (belast u p)) = rev (map swap_step (steps u p)).
Proof.
elim: p u => [|x p IH] u //=.
rewrite rev_cons steps_rcons IH last_rev_belast.
by rewrite rev_cons.
Qed.

Section Sums.
Variable V : nmodType.
Variable f : T -> T -> V.

Definition slen (u : T) (p : seq T) : V := \sum_(e <- steps u p) f e.1 e.2.

Lemma slen_nil u : slen u [::] = 0.
Proof. by rewrite /slen big_nil. Qed.

Lemma slen_cons u x p : slen u (x :: p) = f u x + slen x p.
Proof. by rewrite /slen steps_cons big_cons. Qed.

Lemma slen_cat u p q : slen u (p ++ q) = slen u p + slen (last u p) q.
Proof. by rewrite /slen steps_cat big_cat. Qed.

Lemma slen_rcons u p x : slen u (rcons p x) = slen u p + f (last u p) x.
Proof. by rewrite /slen steps_rcons -cats1 big_cat big_seq1. Qed.

Lemma slen_rev u p : (forall x y, f x y = f y x) ->
  slen (last u p) (rev (belast u p)) = slen u p.
Proof.
move=> fs; rewrite /slen steps_rev big_rev big_map.
by apply: eq_bigr => -[x y] _ /=; rewrite fs.
Qed.

End Sums.
End Steps.

Lemma path_steps (T : Type) (e : rel T) u p :
  path e u p = all (fun st => e st.1 st.2) (steps u p).
Proof. by elim: p u => [|x p IH] u //=; rewrite IH. Qed.

(** Sums over a subsequence. *)
Lemma sum_subseq (R : numDomainType) (X : eqType) (f : X -> R) (s1 s2 : seq X) :
  (forall x, x \in s2 -> 0 <= f x) -> subseq s1 s2 ->
  \sum_(x <- s1) f x <= \sum_(x <- s2) f x.
Proof.
elim: s2 s1 => [|y s2 IH] [|x s1] //= f0.
- by move=> _; rewrite big_nil big_seq; apply: sumr_ge0 => z /f0.
have f0' : forall z, z \in s2 -> 0 <= f z by move=> z zs; apply: f0; rewrite in_cons zs orbT.
case: eqP => [<-|_] sub.
- by rewrite !big_cons lerD2l IH.
apply: le_trans (IH _ f0' sub) _.
by rewrite big_cons lerDr f0 ?mem_head.
Qed.

Lemma sum_subseq_lt (R : numDomainType) (X : eqType) (f : X -> R) (s1 s2 : seq X) :
  (forall x, x \in s2 -> 0 < f x) -> subseq s1 s2 -> (size s1 < size s2)%N ->
  \sum_(x <- s1) f x < \sum_(x <- s2) f x.
Proof.
elim: s2 s1 => [|y s2 IH] [|x s1] //= f0.
- move=> _ _; rewrite big_nil big_cons; apply: ltr_wpDr; last exact/f0/mem_head.
  by rewrite big_seq; apply: sumr_ge0 => z zs; apply/ltW/f0; rewrite in_cons zs orbT.
have f0' : forall z, z \in s2 -> 0 < f z by move=> z zs; apply: f0; rewrite in_cons zs orbT.
case: eqP => [<-|_] sub; rewrite ltnS => sz.
- by rewrite !big_cons ltrD2l IH.
apply: le_lt_trans (sum_subseq _ sub) _ => [z /f0'/ltW //|].
by rewrite big_cons ltrDr f0 ?mem_head.
Qed.

(** * Shortening a walk to a path *)
Section Shorten.
Variable G : sgraph.

Lemma uniq_cons_rcons (u x : G) p :
  uniq (u :: rcons p x) = (x \notin u :: p) && uniq (u :: p).
Proof. by rewrite -rcons_cons rcons_uniq. Qed.

Lemma shorten_walk (u : G) p : path (--) u p ->
  exists q, [/\ path (--) u q, last u q = last u p, uniq (u :: q),
    subseq (steps u q) (steps u p) &
    (if uniq (u :: p) then q = p else (size q < size p)%N)].
Proof.
elim/last_ind: p => [|p x IH]; first by move=> _; exists [::]; split.
rewrite rcons_path => /andP[pp px].
have [q [qp ql qu qs qe]] := IH pp.
have szq : (size q <= size p)%N.
  by rewrite -(size_steps u q) -(size_steps u p); apply: size_subseq.
have stp : subseq (steps u p) (steps u (rcons p x)).
  by rewrite steps_rcons; apply: subseq_rcons.
rewrite uniq_cons_rcons last_rcons.
case: (boolP (x \in u :: q)) => xq.
- have -> : (x \notin u :: p) && uniq (u :: p) = false.
    case: (boolP (uniq (u :: p))) qe => [_ qe|_ _]; last by rewrite andbF.
    by rewrite -qe xq.
  rewrite in_cons in xq; case: (eqVneq x u) xq => [-> _|xu /= xq].
    exists [::]; split=> //; first by rewrite /steps /= sub0seq.
    by rewrite size_rcons.
  case/splitPr: xq qp ql qu qs qe szq => q1 q2 qp ql qu qs qe szq.
  exists (rcons q1 x); split.
  + by move: qp; rewrite cat_path rcons_path => /andP[-> /= /andP[]].
  + by rewrite last_rcons.
  + by move: qu; rewrite -cat_rcons -cat_cons cat_uniq => /and3P[].
  + apply: subseq_trans stp; apply: subseq_trans qs.
    by rewrite -cat_rcons steps_cat prefix_subseq.
  + rewrite !size_rcons ltnS; apply: leq_trans szq.
    by rewrite size_cat /= addnS ltnS leq_addr.
- exists (rcons q x); split.
  + by rewrite rcons_path qp ql px.
  + by rewrite last_rcons.
  + by rewrite uniq_cons_rcons xq qu.
  + by rewrite !steps_rcons ql -!cats1 cat_subseq.
  + case: (boolP (uniq (u :: p))) qe => [pu qe|_ qe].
      by rewrite qe in xq *; rewrite xq.
    by rewrite andbF !size_rcons ltnS.
Qed.

End Shorten.

(** * Finite enumeration of short sequences *)
Section Enum.
Variable T : finType.

Fixpoint allseqs (n : nat) : seq (seq T) :=
  if n is n'.+1 then [::] :: [seq x :: s | x <- enum T, s <- allseqs n'] else [:: [::]].

Lemma mem_allseqs n s : (size s <= n)%N -> s \in allseqs n.
Proof.
elim: n s => [|n IH] [|x s] //= sz.
by rewrite in_cons /=; apply: (allpairs_f (fun x s => x :: s)); rewrite ?mem_enum ?IH.
Qed.

Lemma size_uniq_card (s : seq T) : uniq s -> (size s <= #|T|)%N.
Proof. by move=> us; rewrite cardT; apply: uniq_leq_size => // x; rewrite mem_enum. Qed.

End Enum.

Lemma list_min (R : realDomainType) (X : eqType) (f : X -> R) (s : seq X) :
  s != [::] -> exists2 m, m \in s & forall y, y \in s -> f m <= f y.
Proof.
elim: s => [|x s IH] // _; case: (eqVneq s [::]) => [->|sn].
  by exists x => [|y]; rewrite ?mem_head // inE => /eqP ->.
have [m ms mmin] := IH sn; case: (leP (f x) (f m)) => [xm|mx].
- exists x => [|y]; first exact: mem_head.
  by rewrite inE => /orP[/eqP ->//|/mmin]; apply: le_trans.
- exists m => [|y]; first by rewrite inE ms orbT.
  by rewrite inE => /orP[/eqP ->|/mmin//]; apply: ltW.
Qed.

(** * Weighted walks: shortest walks exist, are paths, and tightness is decidable *)
Section Weighted.
Variable R : realFieldType.
Variable G : sgraph.
Variable w : G -> G -> R.
Hypothesis hw : edge_length w.

Lemma wlenE u p : wlen w u p = slen w u p.
Proof. by []. Qed.

Lemma wlen_ge0 u p : path (--) u p -> 0 <= wlen w u p.
Proof.
rewrite path_steps wlenE /slen big_seq => /allP pa; apply: sumr_ge0 => e /pa ee.
exact/ltW/hw.1.
Qed.

Lemma wlen_subseq u p q : path (--) u p -> subseq (steps u q) (steps u p) ->
  wlen w u q <= wlen w u p.
Proof.
rewrite path_steps => /allP pa sub; apply: (sum_subseq (f := fun e => w e.1 e.2)) => //.
by move=> e /pa ee; apply/ltW/hw.1.
Qed.

Lemma wlen_subseq_lt u p q : path (--) u p -> subseq (steps u q) (steps u p) ->
  (size q < size p)%N -> wlen w u q < wlen w u p.
Proof.
rewrite path_steps => /allP pa sub sz.
apply: (sum_subseq_lt (f := fun e => w e.1 e.2)) => //; first by move=> e /pa; apply: hw.1.
by rewrite !size_steps.
Qed.

Definition uwalks (u v : G) : seq (seq G) :=
  [seq p <- allseqs G #|G| | [&& path (--) u p, last u p == v & uniq (u :: p)]].

Lemma mem_uwalks u v p :
  (p \in uwalks u v) = [&& path (--) u p, last u p == v & uniq (u :: p)].
Proof.
rewrite mem_filter; case: and3P => //= -[_ _ up]; apply: mem_allseqs.
by apply: size_uniq_card; case/andP: up.
Qed.

(** Every walk has a path inside [uwalks] that is no longer. *)
Lemma uwalks_below u p : path (--) u p ->
  exists2 q, q \in uwalks u (last u p) & wlen w u q <= wlen w u p.
Proof.
move=> pp; have [q [qp ql qu qs _]] := shorten_walk pp.
by exists q; [rewrite mem_uwalks qp ql eqxx qu | apply: wlen_subseq].
Qed.

Lemma shortest_ex u p : path (--) u p ->
  exists q, shortest_walk w u (last u p) q /\ uniq (u :: q).
Proof.
move=> pp; have [q0 q0u _] := uwalks_below pp.
have [|m mu mmin] := list_min (wlen w u) (s := uwalks u (last u p)).
  by apply/eqP => e; rewrite e in q0u.
move: (mu); rewrite mem_uwalks => /and3P[mp /eqP ml muq]; exists m; split=> //; split=> //.
move=> r rp rl; have [r' r'u r'le] := uwalks_below rp.
by apply: le_trans (mmin _ _) r'le; rewrite rl in r'u.
Qed.

Lemma shortest_path u v p : shortest_walk w u v p -> path (--) u p.
Proof. by case. Qed.

Lemma shortest_last u v p : shortest_walk w u v p -> last u p = v.
Proof. by case. Qed.

Lemma shortest_uniq u v p : shortest_walk w u v p -> uniq (u :: p).
Proof.
case=> pp pl pmin; case: (boolP (uniq (u :: p))) => // nu.
have [q [qp ql _ qs]] := shorten_walk pp; rewrite (negbTE nu) => sz.
have := pmin q qp; rewrite ql pl => /(_ erefl).
by rewrite leNgt (wlen_subseq_lt pp qs sz).
Qed.

Lemma shortest_nil u : shortest_walk w u u [::].
Proof. by split=> // q qp _; rewrite /wlen big_nil; apply: wlen_ge0. Qed.

(** Tightness of an edge: the one-step walk is a shortest walk. *)
Definition tightb (u v : G) : bool := all (fun p => w u v <= wlen w u p) (uwalks u v).

Lemma wlen1 u v : wlen w u [:: v] = w u v.
Proof. by rewrite wlenE slen_cons slen_nil addr0. Qed.

Lemma tightP u v : u -- v -> reflect (shortest_walk w u v [:: v]) (tightb u v).
Proof.
move=> uv; apply: (iffP allP) => [ht|[_ _ hmin] p].
- split; rewrite /= ?uv // => q qp ql; rewrite wlen1.
  have [q' q'u q'le] := uwalks_below qp; rewrite ql in q'u.
  exact: le_trans (ht _ q'u) q'le.
- rewrite mem_uwalks => /and3P[pp /eqP pl _]; rewrite -wlen1; exact: hmin.
Qed.

End Weighted.

(** * Closed walks: cyclic steps and sums over them *)
Section Cyclic.
Variable T : eqType.

Definition cyc_steps (c : seq T) : seq (T * T) := zip c (rot 1 c).

Lemma cyc_steps_cons z s : cyc_steps (z :: s) = steps z (rcons s z).
Proof.
by rewrite /cyc_steps rot1_cons /steps -rcons_cons zip_rcons_l // size_rcons.
Qed.

Lemma cyc_steps_rot k c : cyc_steps (rot k c) = rot k (cyc_steps c).
Proof. by rewrite /cyc_steps rot_rot zip_rot // size_rot. Qed.

Lemma cyc_edgeE (c : seq T) x y :
  seq_cyclic_consecutiveb c x y = ((x, y) \in cyc_steps c) || ((y, x) \in cyc_steps c).
Proof. by []. Qed.

Lemma cyc_edge_rot k (c : seq T) x y :
  seq_cyclic_consecutiveb (rot k c) x y = seq_cyclic_consecutiveb c x y.
Proof. by rewrite !cyc_edgeE cyc_steps_rot !mem_rot. Qed.

Lemma cyc_steps_uniq (c : seq T) : uniq c -> uniq (cyc_steps c).
Proof. exact: zip_uniql. Qed.

Section CSum.
Variable V : nmodType.
Variable f : T -> T -> V.

Definition csum (c : seq T) : V := \sum_(e <- cyc_steps c) f e.1 e.2.

Lemma csum_cons z s : csum (z :: s) = slen f z (rcons s z).
Proof. by rewrite /csum cyc_steps_cons. Qed.

Lemma csum_rot k c : csum (rot k c) = csum c.
Proof. by rewrite /csum cyc_steps_rot; apply: perm_big; rewrite perm_rot. Qed.

End CSum.

Lemma not_uniq_split (s : seq T) : ~~ uniq s ->
  exists s1 y s2 s3, s = s1 ++ y :: s2 ++ y :: s3.
Proof.
elim: s => [|x s IH] //=; rewrite negb_and negbK => /orP[/splitPr[s2 s3]|/IH].
  by exists [::], x, s2, s3.
by move=> [s1 [y [s2 [s3 ->]]]]; exists (x :: s1), y, s2, s3.
Qed.

End Cyclic.

(** * The minimal odd closed walk: a closed walk with an odd number of D-steps yields a geodesic
    cycle with an odd number of D-steps *)
Section MinOdd.
Variable R : realFieldType.
Variable G : sgraph.
Variable w : G -> G -> R.
Hypothesis hw : edge_length w.
Variable D : rel G.
Hypothesis Dsym : symmetric D.

Let wsym : forall x y, w x y = w y x := hw.2.
Let Dnsym : forall x y : G, (D x y : nat) = D y x.
Proof. by move=> x y; rewrite Dsym. Qed.

Definition cw (c : seq G) : R := csum w c.
Definition dc (c : seq G) : nat := csum (fun x y => (D x y : nat)) c.

Lemma rev_walk_path (u : G) (p : seq G) : path (--) u p -> path (--) (last u p) (rev (belast u p)).
Proof.
by rewrite rev_path; apply: sub_path => x y; rewrite sg_sym.
Qed.

(** Splitting a closed walk at a repeated vertex. *)
Lemma split_closed (c : seq G) : cycle (--) c -> ~~ uniq c ->
  exists K1 K2, [/\ cycle (--) K1, cycle (--) K2,
    (size K1 < size c)%N /\ (size K2 < size c)%N,
    cw c = cw K1 + cw K2 & dc c = (dc K1 + dc K2)%N].
Proof.
move=> cc /not_uniq_split [s1 [y [s2 [s3 ce]]]].
have cr : rot (size s1) c = y :: s2 ++ y :: (s3 ++ s1).
  by rewrite ce rot_size_cat cat_cons -catA.
have e1 : rcons (s2 ++ y :: (s3 ++ s1)) y = rcons s2 y ++ rcons (s3 ++ s1) y.
  by rewrite -cat_rcons rcons_cat.
exists (y :: s2), (y :: (s3 ++ s1)).
move: cc; rewrite -(rot_cycle (size s1)) cr /= e1 cat_path last_rcons => /andP[c1 c2].
split=> //.
- rewrite ce !size_cat /= !size_cat /=; split.
    by rewrite addnS ltnS (leq_trans _ (leq_addl (size s1) _)) // addnS ltnS leq_addr.
  by rewrite addnS ltnS [(size s3 + _)%N]addnC -addnS leq_add2l leq_addl.
- by rewrite /cw -(csum_rot _ (size s1)) cr !csum_cons e1 slen_cat last_rcons.
- by rewrite /dc -(csum_rot _ (size s1)) cr !csum_cons e1 slen_cat last_rcons.
Qed.

Lemma rot_split (c : seq G) u v : uniq c -> u \in c -> v \in c -> u != v ->
  exists k s1 s2, rot k c = u :: s1 ++ v :: s2.
Proof.
move=> cu /splitPr[c1 c2] vc uv; exists (size c1); rewrite rot_size_cat.
have : v \in c2 ++ c1.
  by move: vc; rewrite !mem_cat in_cons eq_sym (negbTE uv) /= orbC.
by rewrite cat_cons; case/splitPr=> s1 s2; exists s1, s2.
Qed.

Lemma on_cycle_walk_steps (c : seq G) u p :
  on_cycle_walk c u p = all (fun e => seq_cyclic_consecutiveb c e.1 e.2) (steps u p).
Proof. by []. Qed.

(** One pair of cycle vertices: either some arc is a shortest walk, or a shortest walk lighter
    than both arcs splits the closed walk into two lighter closed walks, one of them odd. *)
Lemma pair_step (c : seq G) u v : ucycle (--) c -> u \in c -> v \in c -> odd (dc c) ->
  (exists p, shortest_walk w u v p /\ on_cycle_walk c u p) \/
  (exists K, [/\ cycle (--) K, odd (dc K) & cw K < cw c]).
Proof.
move=> /andP[cc cu] uc vc oc.
case: (eqVneq u v) => [<-|uv]; first by left; exists [::]; split; [exact: shortest_nil|].
have [k [s1 [s2 cr]]] := rot_split cu uc vc uv.
pose a1 := rcons s1 v; pose a2 := rcons (rev s2) v.
have e1 : rcons (s1 ++ v :: s2) u = a1 ++ rcons s2 u by rewrite rcons_cat rcons_cons cat_rcons.
have := cc; rewrite -(rot_cycle k) cr /= e1 cat_path last_rcons => /andP[pa1 pb].
have pa2 : path (--) u a2.
  by have := rev_walk_path pb; rewrite last_rcons belast_rcons rev_cons.
have ra2 : forall (V : nmodType) (f : G -> G -> V), (forall x y, f x y = f y x) ->
    slen f u a2 = slen f v (rcons s2 u).
  by move=> V f fs; rewrite -(slen_rev v (rcons s2 u) fs) last_rcons belast_rcons rev_cons.
have csc : forall (V : nmodType) (f : G -> G -> V), (forall x y, f x y = f y x) ->
    csum f c = slen f u a1 + slen f u a2.
  by move=> V f fs; rewrite -(csum_rot _ k) cr csum_cons e1 slen_cat last_rcons (ra2 _ _ fs).
have stc : steps u a1 ++ steps v (rcons s2 u) = cyc_steps (rot k c).
  by rewrite cr cyc_steps_cons e1 steps_cat last_rcons.
have oa1 : on_cycle_walk c u a1.
  rewrite on_cycle_walk_steps; apply/allP => -[x y] e; rewrite -(cyc_edge_rot k) cyc_edgeE.
  by rewrite -stc mem_cat e.
have oa2 : on_cycle_walk c u a2.
  rewrite on_cycle_walk_steps; apply/allP => -[x y] e; rewrite -(cyc_edge_rot k) cyc_edgeE.
  have : (y, x) \in steps v (rcons s2 u).
    move: e; rewrite /a2 -rev_cons -(belast_rcons v s2 u) -{1}(last_rcons v s2 u) steps_rev.
    by rewrite mem_rev; case/mapP=> -[x' y'] e' [-> ->].
  by move=> yx /=; apply/orP; right; rewrite -stc mem_cat yx orbT.
have [P [sP _]] := shortest_ex hw pa1; rewrite last_rcons in sP.
have [pP lP minP] := sP.
case: (leP (wlen w u a1) (wlen w u P)) => h1.
  left; exists a1; split=> //; split=> //; first by rewrite last_rcons.
  by move=> q qp ql; exact: le_trans h1 (minP q qp ql).
case: (leP (wlen w u a2) (wlen w u P)) => h2.
  left; exists a2; split=> //; split=> //; first by rewrite /a2 last_rcons.
  by move=> q qp ql; exact: le_trans h2 (minP q qp ql).
right; clear sP; case/lastP: P pP lP minP h1 h2 => [|P' x] pP.
  by move=> /= uv'; rewrite uv' eqxx in uv.
rewrite last_rcons => xv; subst x => minP h1 h2.
have rP : path (--) v (rcons (rev P') u).
  by have := rev_walk_path pP; rewrite last_rcons belast_rcons rev_cons.
have rPs : forall (V : nmodType) (f : G -> G -> V), (forall x y, f x y = f y x) ->
    slen f v (rcons (rev P') u) = slen f u (rcons P' v).
  by move=> V f fs; rewrite -(slen_rev u (rcons P' v) fs) last_rcons belast_rcons rev_cons.
have k1 : rcons (s1 ++ v :: rev P') u = a1 ++ rcons (rev P') u.
  by rewrite rcons_cat rcons_cons cat_rcons.
have k2 : rcons (P' ++ v :: s2) u = rcons P' v ++ rcons s2 u.
  by rewrite rcons_cat rcons_cons cat_rcons.
have cK1 : forall (V : nmodType) (f : G -> G -> V), (forall x y, f x y = f y x) ->
    csum f (u :: s1 ++ v :: rev P') = slen f u a1 + slen f u (rcons P' v).
  by move=> V f fs; rewrite csum_cons k1 slen_cat last_rcons (rPs _ _ fs).
have cK2 : forall (V : nmodType) (f : G -> G -> V), (forall x y, f x y = f y x) ->
    csum f (u :: P' ++ v :: s2) = slen f u (rcons P' v) + slen f u a2.
  by move=> V f fs; rewrite csum_cons k2 slen_cat last_rcons (ra2 _ _ fs).
have cyK1 : cycle (--) (u :: s1 ++ v :: rev P').
  by rewrite /= k1 cat_path last_rcons pa1 rP.
have cyK2 : cycle (--) (u :: P' ++ v :: s2).
  by rewrite /= k2 cat_path last_rcons pP pb.
have dK : (dc (u :: s1 ++ v :: rev P') + dc (u :: P' ++ v :: s2) =
    dc c + 2 * slen (fun x y => (D x y : nat)) u (rcons P' v))%N.
  rewrite /dc (cK1 _ _ Dnsym) (cK2 _ _ Dnsym) (csc _ _ Dnsym).
  move: (slen _ u a1) (slen _ u (rcons P' v)) (slen _ u a2) => a b d.
  change ((a + b) + (b + d) = (a + d) + 2 * b)%N.
  by rewrite mul2n -addnn [RHS]addnACA [(d + b)%N]addnC.
have : odd (dc (u :: s1 ++ v :: rev P') + dc (u :: P' ++ v :: s2)).
  by rewrite dK oddD oc mul2n odd_double.
rewrite oddD; case: (boolP (odd (dc (u :: s1 ++ v :: rev P')))) => o1 o2.
- exists (u :: s1 ++ v :: rev P'); split=> //.
  by rewrite /cw (cK1 _ _ wsym) (csc _ _ wsym) ltrD2l.
- exists (u :: P' ++ v :: s2); split=> //.
  by rewrite /cw (cK2 _ _ wsym) (csc _ _ wsym) ltrD2r.
Qed.

Lemma cw_ge0 (c : seq G) : cycle (--) c -> 0 <= cw c.
Proof. by case: c => [|z s] cc; rewrite /cw ?csum_cons; [rewrite /csum big_nil | apply: wlen_ge0]. Qed.

(** The induction measure: the number of edge sets no heavier than the closed walk. *)
Definition ws (A : {set G * G}) : R := \sum_(e in A) w e.1 e.2.
Definition msr (c : seq G) : nat := #|[set A : {set G * G} | ws A <= cw c]|.

Lemma msr_le (c K : seq G) : cw K <= cw c -> (msr K <= msr c)%N.
Proof.
by move=> h; apply: subset_leq_card; apply/subsetP => A; rewrite !inE => hA; exact: le_trans hA h.
Qed.

Lemma ws_cyc (c : seq G) : uniq c -> ws [set e in cyc_steps c] = cw c.
Proof.
move=> cu; rewrite /ws /cw /csum (big_uniq _ (cyc_steps_uniq cu)).
by apply: eq_bigl => e; rewrite inE.
Qed.

Lemma msr_lt (c K : seq G) : uniq c -> cw K < cw c -> (msr K < msr c)%N.
Proof.
move=> cu h; apply: proper_card; apply/properP; split.
  by apply/subsetP => A; rewrite !inE => hA; exact: le_trans hA (ltW h).
by exists [set e in cyc_steps c]; rewrite !inE (ws_cyc cu) ?lexx // leNgt h.
Qed.

Lemma size3_of_odd (c : seq G) : ucycle (--) c -> odd (dc c) -> (2 < size c)%N.
Proof.
case: c => [|x [|y [|z c]]] //.
- by rewrite /dc /csum big_nil.
- by rewrite /ucycle /= sg_irrefl.
- move=> _; rewrite /dc csum_cons /slen /steps /= !big_cons big_nil.
  by rewrite /= (Dsym y x); case: (D x y).
Qed.

Lemma all_or (X : eqType) (s : seq X) (P : X -> Prop) (Q : Prop) :
  (forall x, x \in s -> P x \/ Q) -> (forall x, x \in s -> P x) \/ Q.
Proof.
elim: s => [|x s IH] h; first by left.
case: (h x (mem_head _ _)) => [px|q]; last by right.
case: IH => [y ys|hs|q]; last by right.
- by apply: h; rewrite inE ys orbT.
- by left => y; rewrite inE => /orP[/eqP ->|/hs].
Qed.

(** The minimal odd closed walk is a geodesic cycle. *)
Theorem min_odd (c : seq G) : cycle (--) c -> odd (dc c) ->
  exists c', [/\ geodesic_cycle w c', odd (dc c') & (2 < size c')%N].
Proof.
have [n] := ubnP (msr c); elim: n c => [|n IHn] c; first by rewrite ltn0.
move=> hn; have [k] := ubnP (size c); elim: k c hn => [|k IHk] c; first by rewrite ltn0.
move=> hn hk cc oc.
case: (boolP (uniq c)) => cu.
- have uc : ucycle (--) c by rewrite /ucycle cc cu.
  have := @all_or _ [seq (x, y) | x <- c, y <- c]
    (fun xy => exists p, shortest_walk w xy.1 xy.2 p /\ on_cycle_walk c xy.1 p)
    (exists K, [/\ cycle (--) K, odd (dc K) & cw K < cw c]).
  case => [xy /allpairsP[[x y] [/= xc yc ->]]|hall|[K [cK oK lK]]].
  + exact: pair_step.
  + exists c; split=> //; last exact: size3_of_odd.
    by split=> // u v uc' vc'; exact: (hall (u, v) (allpairs_f (fun x y => (x, y)) uc' vc')).
  + by apply: (IHn K) => //; exact: leq_trans (msr_lt cu lK) hn.
- have [K1 [K2 [c1 c2 [s1 s2] ew ed]]] := split_closed cc cu.
  have : odd (dc K1) || odd (dc K2) by move: oc; rewrite ed oddD; case: (odd (dc K1)).
  have l1 : cw K1 <= cw c by rewrite ew lerDl cw_ge0.
  have l2 : cw K2 <= cw c by rewrite ew lerDr cw_ge0.
  case/orP => oK.
  + apply: (IHk K1) => //; first exact: leq_ltn_trans (msr_le l1) hn.
    exact: leq_trans s1 hk.
  + apply: (IHk K2) => //; first exact: leq_ltn_trans (msr_le l2) hn.
    exact: leq_trans s2 hk.
Qed.

End MinOdd.

(** * Perturbation: w' = w + eps * gamma keeps every w'-shortest walk w-shortest and separates walks
    with different gamma-lengths *)
Section Perturb.
Variable R : realFieldType.
Variable G : sgraph.
Variable w : G -> G -> R.
Hypothesis hw : edge_length w.
Variable gam : G -> G -> R.
Hypothesis gam_sym : forall x y, gam x y = gam y x.
Variable Gam : R.
Hypothesis gam_ge0 : forall x y, 0 <= gam x y.
Hypothesis gam_le : forall x y, gam x y <= Gam.
Hypothesis Gam_ge0 : 0 <= Gam.

Let N := #|G|.

Definition gaps : seq R :=
  [seq d <- [seq wlen w t.1 t.2.2 - wlen w t.1 t.2.1 |
             t <- [seq (x, pq) | x <- enum G, pq <- [seq (P, Q) | P <- allseqs G N, Q <- allseqs G N]]]
  | 0 < d].

Definition gap : R := foldr Num.min 1 gaps.

Lemma foldr_min_gt0 (s : seq R) : (forall d, d \in s -> 0 < d) -> 0 < foldr Num.min 1 s.
Proof.
elim: s => [|d s IH] h /=; first exact: ltr01.
by rewrite lt_min h ?mem_head // IH // => e es; apply: h; rewrite inE es orbT.
Qed.

Lemma foldr_min_le (s : seq R) d : d \in s -> foldr Num.min 1 s <= d.
Proof.
elim: s => [|e s IH] //=; rewrite inE => /orP[/eqP ->|ds]; first by rewrite ge_min lexx.
by rewrite ge_min IH ?orbT.
Qed.

Lemma gap_gt0 : 0 < gap.
Proof. by apply: foldr_min_gt0 => d; rewrite mem_filter => /andP[]. Qed.

Lemma gap_le u P Q : uniq (u :: P) -> uniq (u :: Q) -> wlen w u P < wlen w u Q ->
  gap <= wlen w u Q - wlen w u P.
Proof.
move=> uP uQ lt; apply: foldr_min_le; rewrite mem_filter subr_gt0 lt /=.
apply/mapP; exists (u, (P, Q)) => //.
apply: (allpairs_f (fun x pq => (x, pq))); first by rewrite mem_enum.
apply: (allpairs_f (fun P Q => (P, Q))); apply: mem_allseqs; apply: size_uniq_card.
  by case/andP: uP.
by case/andP: uQ.
Qed.

Definition eps : R := gap / (Gam * N%:R + 1).

Lemma eps_gt0 : 0 < eps.
Proof.
rewrite /eps divr_gt0 ?gap_gt0 //; apply: lt_le_trans ltr01 _.
by rewrite lerDr mulr_ge0.
Qed.

Lemma sum_le_const (X : Type) (s : seq X) (f : X -> R) c :
  (forall x, f x <= c) -> \sum_(x <- s) f x <= c *+ size s.
Proof.
move=> fc; elim: s => [|x s IH]; first by rewrite big_nil.
by rewrite big_cons mulrS lerD.
Qed.

Lemma wlen_gam_le u P : uniq (u :: P) -> wlen gam u P <= Gam * N%:R.
Proof.
move=> uP; apply: le_trans (sum_le_const _ (fun e => gam_le e.1 e.2)) _.
rewrite size_steps -mulr_natr ler_wpM2l // ler_nat.
by apply: leq_trans (leqnSn _) _; exact: (size_uniq_card uP).
Qed.

Lemma eps_bound u P : uniq (u :: P) -> eps * wlen gam u P < gap.
Proof.
move=> uP; have A0 : 0 < Gam * N%:R + 1 by apply: lt_le_trans ltr01 _; rewrite lerDr mulr_ge0.
rewrite /eps mulrAC ltr_pdivrMr //.
apply: le_lt_trans (ler_wpM2l (ltW gap_gt0) (wlen_gam_le uP)) _.
by rewrite ltr_pM2l ?gap_gt0 // ltrDl ltr01.
Qed.

Definition wpert : G -> G -> R := fun x y => w x y + eps * gam x y.

Lemma wlen_pert u p : wlen wpert u p = wlen w u p + eps * wlen gam u p.
Proof. by rewrite /wlen big_split /= mulr_sumr. Qed.

Lemma edge_length_pert : edge_length wpert.
Proof.
split=> [x y xy|x y]; last by rewrite /wpert hw.2 gam_sym.
apply: lt_le_trans (hw.1 x y xy) _.
by rewrite /wpert lerDl mulr_ge0 // ltW // eps_gt0.
Qed.

(** A shortest walk for the perturbed lengths is a shortest walk for the original ones. *)
Lemma shortest_pert u v P : shortest_walk wpert u v P -> shortest_walk w u v P.
Proof.
move=> sP; have uP := shortest_uniq edge_length_pert sP.
case: sP => pP lP minP; split=> // r pr lr.
have [Q [sQ uQ]] := shortest_ex hw pr; rewrite lr in sQ.
case: (leP (wlen w u P) (wlen w u Q)) => h.
  by apply: le_trans h _; case: sQ => _ _; apply.
exfalso.
have := minP Q (shortest_path sQ) (shortest_last sQ); rewrite !wlen_pert => h'.
have g1 := gap_le uQ uP h.
have g2 := eps_bound uQ.
have eP : 0 <= eps * wlen gam u P.
  by rewrite mulr_ge0 ?(ltW eps_gt0) // /wlen; apply: sumr_ge0 => e _; exact: gam_ge0.
have h2 : wlen w u P <= wlen w u Q + eps * wlen gam u Q by apply: le_trans h'; rewrite lerDl.
have h3 : wlen w u P - wlen w u Q <= eps * wlen gam u Q by rewrite lerBlDl.
by have := lt_le_trans g2 (le_trans g1 h3); rewrite ltxx.
Qed.

Lemma geodesic_pert c : geodesic_cycle wpert c -> geodesic_cycle w c.
Proof.
case=> uc h; split=> // u v uc' vc'; have [p [sp op]] := h u v uc' vc'.
by exists p; split=> //; exact: shortest_pert.
Qed.

(** Uniq walks from the same vertex with different gamma-lengths get different perturbed lengths. *)
Lemma pert_separates u P Q : uniq (u :: P) -> uniq (u :: Q) ->
  wlen gam u P != wlen gam u Q -> wlen wpert u P != wlen wpert u Q.
Proof.
have key : forall A B, uniq (u :: A) -> uniq (u :: B) ->
    wlen w u A < wlen w u B -> wlen wpert u A < wlen wpert u B.
  move=> A B uA uB lt; rewrite !wlen_pert.
  have g := lt_le_trans (eps_bound uA) (gap_le uA uB lt).
  have eB : 0 <= eps * wlen gam u B.
    by rewrite mulr_ge0 ?(ltW eps_gt0) // /wlen; apply: sumr_ge0 => e _; exact: gam_ge0.
  apply: lt_le_trans (_ : wlen w u B <= _); last by rewrite lerDl.
  by rewrite -ltrBrDl.
move=> uP uQ ne; case: (ltgtP (wlen w u P) (wlen w u Q)) => h.
- by rewrite lt_eqF // key.
- by rewrite gt_eqF // key.
rewrite !wlen_pert h; apply: contra ne => /eqP e.
by apply/eqP; apply: (mulfI (lt0r_neq0 eps_gt0)); apply: (addrI (wlen w u Q)).
Qed.

End Perturb.

(** * The counterexample G8: a K4 core B and one vertex in each face of the tetrahedron *)
Section G8.

Definition g8_adj (x y : bool * 'I_4) : bool := (x.2 != y.2) && ~~ (x.1 && y.1).

Lemma g8_sym : symmetric g8_adj.
Proof. by move=> x y; rewrite /g8_adj eq_sym [x.1 && _]andbC. Qed.

Lemma g8_irrefl : irreflexive g8_adj.
Proof. by move=> x; rewrite /g8_adj eqxx. Qed.

Definition G8 : sgraph := SGraph g8_sym g8_irrefl.

Definition o4 (n : nat) : 'I_4 :=
  match n with
  | 0 => @Ordinal 4 0 isT | 1 => @Ordinal 4 1 isT | 2 => @Ordinal 4 2 isT | _ => @Ordinal 4 3 isT
  end.
Definition bv (n : nat) : G8 := (false, o4 n).
Definition sv (n : nat) : G8 := (true, o4 n).

Definition I4 : seq 'I_4 :=
  [:: @Ordinal 4 0 isT; @Ordinal 4 1 isT; @Ordinal 4 2 isT; @Ordinal 4 3 isT].
Definition V8 : seq G8 := [seq (b, i) | b <- [:: false; true], i <- I4].

Lemma mem_I4 (i : 'I_4) : i \in I4.
Proof. by case: i => [[|[|[|[|]]]] ?]. Qed.

Lemma mem_V8 (x : G8) : x \in V8.
Proof. by case: x => [[] [[|[|[|[|]]]] ?]]. Qed.

(** Faces (i, m), i != m: the vertex s_i and the core vertices b_t, t not in {i, m}. *)
Definition face_mem (a : 'I_4 * 'I_4) (x : G8) : bool :=
  if x.1 then x.2 == a.1 else (x.2 != a.1) && (x.2 != a.2).

Definition faces : seq ('I_4 * 'I_4) := [seq im <- [seq (i, m) | i <- I4, m <- I4] | im.1 != im.2].

(** The two core indices of a face, in increasing order. *)
Definition oth (a : 'I_4 * 'I_4) : 'I_4 * 'I_4 :=
  let s := [seq t <- I4 | (t != a.1) && (t != a.2)] in (nth ord0 s 0, nth ord0 s 1).

Definition face_seq (a : 'I_4 * 'I_4) : seq G8 := [:: (true, a.1); (false, (oth a).1); (false, (oth a).2)].

(** Dual path from face (i, m) to the root face (0, 1): the edges it crosses. *)
Definition core1 (i : nat) : nat := if i == 1 then 2 else 1.
Definition core2 (i : nat) : nat := if i == 3 then 2 else 3.

Definition dual_edges (a : 'I_4 * 'I_4) : seq (G8 * G8) :=
  let i := nat_of_ord a.1 in let m := nat_of_ord a.2 in
  if i == 0 then (if m == 1 then [::] else [:: (sv 0, bv (5 - m))])
  else (if m == 0 then [::] else [:: (sv i, bv (6 - i - m))]) ++
       [:: (bv (core1 i), bv (core2 i))] ++
       (if i == 1 then [::] else [:: (sv 0, bv (5 - i))]).

Definition Dface (a : 'I_4 * 'I_4) : rel G8 :=
  fun x y => ((x, y) \in dual_edges a) || ((y, x) \in dual_edges a).

Definition par3 (D : rel G8) (x y z : G8) : bool := odd (D x y + D y z + D z x).

Definition root : 'I_4 * 'I_4 := (@Ordinal 4 0 isT, @Ordinal 4 1 isT).

Definition tri (x y z : G8) : bool := [&& x -- y, y -- z & z -- x].
Definition allB (x y z : G8) : bool := [&& ~~ x.1, ~~ y.1 & ~~ z.1].
Definition infa (a : 'I_4 * 'I_4) (x y z : G8) : bool := [&& face_mem a x, face_mem a y & face_mem a z].

Definition check_par : bool :=
  all (fun a => all (fun x => all (fun y => all (fun z =>
    (tri x y z && ~~ allB x y z) ==> (par3 (Dface a) x y z == infa a x y z (+) infa root x y z)) V8) V8) V8) faces.

Lemma check_par_ok : check_par.
Proof. by vm_compute. Qed.

Lemma allV8 (P : pred G8) : all P V8 -> forall x, P x.
