Qed.

Lemma walk2_shape (T : eqType) (u v s : T) p : uniq (u :: p) -> last u p = v -> u != v ->
  s != v -> {subset p <= [:: s; v]} -> p = [:: v] \/ p = [:: s; v].
Proof.
case: p => [|x [|y [|z p]]] /=.
- by move=> _ ->; rewrite eqxx.
- by move=> _ -> _ _ _; left.
- move=> /and3P[_ xy _] yv _ sv sub; subst y; right; congr (_ :: _).
  have := sub x (mem_head _ _); rewrite !inE => /orP[/eqP //|/eqP xv].
  by move: xy; rewrite xv inE eqxx.
- move=> /and5P[_ xn yn _ _] _ _ sv sub; exfalso.
  have hx := sub x (mem_head _ _).
  have hy : y \in [:: s; v] by apply: sub; rewrite !inE eqxx orbT.
  have hz : z \in [:: s; v] by apply: sub; rewrite !inE eqxx !orbT.
  move: hx hy hz xn yn; rewrite !inE.
  by move=> /orP[/eqP->|/eqP->] /orP[/eqP->|/eqP->] /orP[/eqP->|/eqP->]; rewrite ?eqxx ?orbT.
Qed.

