(** * Extremal.applications.geodesic_cycles_tutte -- a counterexample to the OPG problem "Geodesic cycles and Tutte's
    theorem" as stated (opg:geodesic_cycles_and_tuttes_theorem).

    The row [geodesic_cycles_and_tuttes_theorem_statement] (D2str.v) asserts that every 3-connected finite graph has a
    positive symmetric edge-length assignment for which every geodesic cycle is peripheral (induced, with a connected
    complement). [G8] is the eight-vertex graph of the resolution write-up generated by gpt-6-astra, published at
    https://github.com/graph-theory-AI/Graph-Theory-LLM-Proofs/blob/abcc3defa6684921fe4b460174ea8b2810b5485b/attacks_opg/geodesic_cycles_and_tuttes_theorem/output.md
    (committed 2026-09-16, merged by PR #3 on 2026-09-17, MIT licence): a K4 core b_0..b_3 and, for each i, a vertex s_i
    adjacent to the three core vertices other than b_i (one vertex inside each face of a tetrahedron). It is
    3-connected ([G8_3connected]), and [g8_geodesic_not_peripheral] shows that for EVERY positive symmetric assignment
    some geodesic cycle is not peripheral, so the row fails
    ([geodesic_cycles_and_tuttes_theorem_disproved], at R := rat).

    The proof follows the write-up, reorganised for the kernel:
    - [min_odd]: for a symmetric relation D, a closed walk with an odd number of D-steps yields a geodesic cycle with an
      odd number of D-steps. A lightest such closed walk is geodesic: a shortest walk lighter than both arcs between two
      of its vertices splits it into two lighter closed walks, one of them odd. This replaces the write-up's Fact 1 (the
      geodesic cycles generate the cycle space) together with its dimension count.
    - The perturbed lengths [wpert] = w + eps * gamma (eps from the least positive difference of walk lengths) keep
      every shortest walk shortest, so geodesic cycles stay geodesic, and separate the two 2-paths b_j s_p b_k and
      b_j s_q b_k over each core edge (the write-up's Fact 2, for the comparisons the argument uses).
    - In G8 every chordless cycle is a triangle ([no_long_chordless]) and the core triangles are not peripheral (the
      vertex s_i inside a core triangle is isolated in its complement). Each core triangle therefore has a non-tight
      edge, and the face over such an edge on the side of the longer 2-path is not geodesic ([face_of_edge]). Two such
      faces a and b of distinct edges, and the parity of dual paths from a and from b to a root face, give through
      [min_odd] a geodesic, hence peripheral, face triangle of odd parity, that is a or b: a contradiction.
    The finite facts about G8 are checked by [vm_compute] over explicit lists of its vertices, indices and faces.

    CAVEATS (the write-up's): "peripheral" has its standard meaning, induced and non-separating, as in the row; the
    literature has not been searched for this counterexample, and the row's OPG status is unchanged. *)
