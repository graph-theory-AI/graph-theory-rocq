(** G8 is 3-connected: after deleting at most two vertices, the remaining core vertices form a
    clique and every remaining spoke vertex keeps a core neighbour. *)
Lemma G8_3connected : k_connected G8 3.
Proof.
split; first by rewrite card_prod card_bool card_ord.
move=> S sS; set A := [set: G8] :\: S.
have inA : forall v, (v \in A) = (v \notin S) by move=> v; rewrite !inE andbT.
have tob : forall v, v \in A -> exists b : 'I_4,
    ((false, b) : G8) \in A /\ connect (preliminaries.restrict_mem (mem A) (--)) v (false, b).
  case=> [[] i] vA; last by exists i; split=> //; exact: connect0.
  case: (boolP [exists j : 'I_4, (j != i) && (((false, j) : G8) \in A)]).
    case/existsP => j /andP[ji jA]; exists j; split=> //.
    by apply: connect1; rewrite /= vA jA /= /edge_rel /= /g8_adj /= andbT eq_sym.
  rewrite negb_exists => /forallP h; exfalso.
  have sub : [set ((false, j) : G8) | j in [set~ i]] \subset S.
    apply/subsetP => v /imsetP[j]; rewrite !inE => ji ->.
    by have := h j; rewrite ji /= inA negbK.
  have := subset_leq_card sub; rewrite card_imset; first by move=> j1 j2 [].
  by rewrite cardsC1 card_ord /= => c3; have := leq_ltn_trans c3 sS.
move=> x y xA yA.
have [bx [bxA cx]] := tob x xA; have [b' [byA cy]] := tob y yA.
apply: connect_trans cx _.
have symA : symmetric (preliminaries.restrict_mem (mem A) (--)).
  by move=> u w /=; rewrite sg_sym; case: (u \in A); case: (w \in A).
rewrite (sym_connect_sym symA) in cy; apply: connect_trans _ cy.
case: (eqVneq bx b') => [->|bb]; first exact: connect0.
by apply: connect1; rewrite /= bxA byA /= /edge_rel /= /g8_adj /= andbT.
Qed.

(** The core triangles T_i (the core without b_i). *)
Definition Tl (i : 'I_4) : seq 'I_4 := [seq t <- I4 | t != i].
Definition Tx (i : 'I_4) : G8 := (false, nth ord0 (Tl i) 0).
Definition Ty (i : 'I_4) : G8 := (false, nth ord0 (Tl i) 1).
Definition Tz (i : 'I_4) : G8 := (false, nth ord0 (Tl i) 2).
Definition Tseq (i : 'I_4) : seq G8 := [:: Tx i; Ty i; Tz i].

Definition check_T : bool :=
  all (fun i => [&& tri (Tx i) (Ty i) (Tz i), allB (Tx i) (Ty i) (Tz i), uniq (Tseq i),
    all (fun x => (x \in Tseq i) == (~~ x.1 && (x.2 != i))) V8 &
    all (fun x => all (fun y => [&& x \in Tseq i, y \in Tseq i & x != y] ==>
       seq_cyclic_consecutiveb (Tseq i) x y) V8) V8]) I4.

Lemma check_T_ok : check_T.
Proof. by vm_compute. Qed.

Definition check_oth2 : bool :=
  all (fun j => all (fun k => (j != k) ==>
    all (fun x => (face_mem ((oth (j, k)).1, (oth (j, k)).2) x ==>
                   (x \in [:: (true, (oth (j, k)).1); (false, j); (false, k)])) &&
                  (face_mem ((oth (j, k)).2, (oth (j, k)).1) x ==>
                   (x \in [:: (true, (oth (j, k)).2); (false, j); (false, k)]))) V8) I4) I4.

Lemma check_oth2_ok : check_oth2.
Proof. by vm_compute. Qed.

